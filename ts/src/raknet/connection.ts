import { randomUUID } from 'node:crypto';
import type { AddressInfo, IncomingMessage } from './types.js';
import { Reliability, OFFLINE_MAGIC, MTU_SIZE, MessageId } from './types.js';
import { ReliabilityLayer } from './reliability.js';
import { encodeAddress } from './address.js';
import type { UdpSocket } from './socket.js';

const RAKNET_PROTOCOL_VERSION = 0x0b;

export const enum ConnectionState {
  DISCONNECTED = 0,
  CONNECTING = 1,
  CONNECTED = 2,
  DISCONNECTING = 3,
}

function writeU32BE(buf: Uint8Array, offset: number, val: number): void {
  buf[offset] = (val >>> 24) & 0xff;
  buf[offset + 1] = (val >>> 16) & 0xff;
  buf[offset + 2] = (val >>> 8) & 0xff;
  buf[offset + 3] = val & 0xff;
}

function readU32BE(buf: Uint8Array, offset: number): number {
  return (
    (((buf[offset] ?? 0) << 24) |
      ((buf[offset + 1] ?? 0) << 16) |
      ((buf[offset + 2] ?? 0) << 8) |
      (buf[offset + 3] ?? 0)) >>>
    0
  );
}

/** Key for the internal datagram routing table. Never exposed as an identity. */
function addrKey(remote: AddressInfo): string {
  return `${remote.host}:${String(remote.port)}`;
}

function randomGuid(): Uint8Array {
  const buf = new Uint8Array(8);
  for (let i = 0; i < 8; i++) {
    buf[i] = Math.floor(Math.random() * 256);
  }
  return buf;
}

export interface ClientSession {
  /**
   * Opaque per-connection GUID — NOT derived from the client's address,
   * so it is safe to expose publicly (web UIs, logs). A reconnect is a
   * new session with a new id. Use `session.address` for the endpoint.
   */
  readonly id: string;
  readonly address: AddressInfo;
  playerIndex: number;
  viewIdBase: number;
  viewIdEnd: number;
  state: ConnectionState;
  reliability: ReliabilityLayer;
  /** Random 8-byte value generated by RakNet at client startup, stable across reconnects within the same game process. */
  perGameLaunchId: bigint;
  /** The local port this client connected through. */
  readonly localPort: number;
}

export type PortRemoveMode = 'DisconnectClientsOnPort';

export interface RakNetServerOptions {
  port?: number;
  ports?: number[];
  password?: string;
  /** If provided, called with the connecting session and the password the client sent. Return true to accept. Takes priority over static `password`. */
  passwordPredicate?: (session: ClientSession, password: string) => boolean;
  viewIdStride?: number;
  epochNs?: bigint;
  /** Idle time (ms, no datagram received) before a session is evicted as dead. Default 10000. */
  sessionTimeoutMs?: number;
}

type EventHandler<T extends unknown[]> = (...args: T) => void;

export class RakNetServer {
  private sockets: Map<number, UdpSocket> = new Map();
  private portAccepting: Map<number, boolean> = new Map();
  private sessionSockets: Map<string, UdpSocket> = new Map();
  /** Datagram routing table, keyed by addrKey(remote). Internal only. */
  private sessionsByAddr: Map<string, ClientSession> = new Map();
  /** Public identity map, keyed by ClientSession.id (GUID). */
  private sessionsById: Map<string, ClientSession> = new Map();
  private nextPlayerIndex = 1;
  private freePlayerIndices: number[] = [];
  private readonly password: string;
  private readonly passwordPredicate: ((session: ClientSession, password: string) => boolean) | null;
  private readonly viewIdStride: number;
  private readonly sessionTimeoutMs: number;
  private readonly initialPorts: number[];
  private connectHandlers: Array<EventHandler<[ClientSession]>> = [];
  private disconnectHandlers: Array<EventHandler<[ClientSession]>> = [];
  private messageHandlers: Array<EventHandler<[ClientSession, IncomingMessage]>> = [];
  private tickTimer: ReturnType<typeof setInterval> | null = null;
  private externalSocket: UdpSocket | null = null;

  private readonly epochNs: bigint;

  constructor(
    socketOrOptions: UdpSocket | RakNetServerOptions,
    options?: RakNetServerOptions,
  ) {
    if (options !== undefined) {
      // Legacy form: new RakNetServer(socket, { port, ... })
      this.externalSocket = socketOrOptions as UdpSocket;
      this.initialPorts = options.ports ?? (options.port !== undefined ? [options.port] : []);
      this.password = options.password ?? '';
      this.passwordPredicate = options.passwordPredicate ?? null;
      this.viewIdStride = options.viewIdStride ?? 50;
      this.epochNs = options.epochNs ?? process.hrtime.bigint();
      this.sessionTimeoutMs = options.sessionTimeoutMs ?? 10_000;
    } else {
      const opts = socketOrOptions as RakNetServerOptions;
      this.initialPorts = opts.ports ?? (opts.port !== undefined ? [opts.port] : []);
      this.password = opts.password ?? '';
      this.passwordPredicate = opts.passwordPredicate ?? null;
      this.viewIdStride = opts.viewIdStride ?? 50;
      this.epochNs = opts.epochNs ?? process.hrtime.bigint();
      this.sessionTimeoutMs = opts.sessionTimeoutMs ?? 10_000;
    }
  }

  async start(): Promise<void> {
    if (this.externalSocket) {
      if (this.initialPorts.length > 0) {
        const port = this.initialPorts[0]!;
        this.sockets.set(port, this.externalSocket);
        this.portAccepting.set(port, true);
        this.externalSocket.onMessage((data, remote) => {
          this.handlePacket(data, remote, this.externalSocket!);
        });
        await this.externalSocket.bind(port);
      }
      for (let i = 1; i < this.initialPorts.length; i++) {
        await this.addPort(this.initialPorts[i]!);
      }
    } else {
      for (const port of this.initialPorts) {
        await this.addPort(port);
      }
    }
    this.tickTimer = setInterval(() => {
      this.tick();
    }, 66);
  }

  async stop(): Promise<void> {
    if (this.tickTimer) {
      clearInterval(this.tickTimer);
      this.tickTimer = null;
    }
    for (const session of this.sessionsByAddr.values()) {
      if (session.state === ConnectionState.CONNECTED) {
        session.reliability.queueOutgoing(
          new Uint8Array([MessageId.DISCONNECTION_NOTIFICATION]),
          Reliability.RELIABLE_ORDERED,
        );
        const sock = this.sessionSockets.get(addrKey(session.address));
        if (sock) {
          const packets = session.reliability.getOutgoingPackets();
          for (const p of packets) {
            sock.sendTo(p, session.address.host, session.address.port);
          }
        }
      }
    }
    this.sessionsByAddr.clear();
    this.sessionsById.clear();
    this.sessionSockets.clear();
    for (const sock of this.sockets.values()) {
      await sock.close();
    }
    this.sockets.clear();
    this.portAccepting.clear();
  }

  onConnect(handler: EventHandler<[ClientSession]>): void {
    this.connectHandlers.push(handler);
  }

  onDisconnect(handler: EventHandler<[ClientSession]>): void {
    this.disconnectHandlers.push(handler);
  }

  onMessage(handler: EventHandler<[ClientSession, IncomingMessage]>): void {
    this.messageHandlers.push(handler);
  }

  sendTo(session: ClientSession, payload: Uint8Array, reliability: Reliability, bitLength?: number): void {
    session.reliability.queueOutgoing(payload, reliability, 0, bitLength);
  }

  getSession(id: string): ClientSession | undefined {
    return this.sessionsById.get(id);
  }

  get clients(): ReadonlyMap<string, ClientSession> {
    return this.sessionsById;
  }

  async addPort(port: number): Promise<void> {
    if (this.sockets.has(port)) {
      throw new Error(`Port ${port} is already bound`);
    }
    const { UdpSocket: SocketClass } = await import('./socket.js');
    const sock = new SocketClass();
    sock.onMessage((data, remote) => {
      this.handlePacket(data, remote, sock);
    });
    await sock.bind(port);
    this.sockets.set(port, sock);
    this.portAccepting.set(port, true);
  }

  async removePort(port: number, options: { mode: PortRemoveMode }): Promise<void> {
    void options.mode;
    const sock = this.sockets.get(port);
    if (!sock) {
      throw new Error(`Port ${port} is not bound`);
    }
    for (const session of this.getSessionsByPort(port)) {
      this.disconnectClient(session);
    }
    this.sockets.delete(port);
    this.portAccepting.delete(port);
    await sock.close();
  }

  setPortAccepting(port: number, accepting: boolean): void {
    if (!this.sockets.has(port)) {
      throw new Error(`Port ${port} is not bound`);
    }
    this.portAccepting.set(port, accepting);
  }

  getSocket(port: number): UdpSocket | undefined {
    return this.sockets.get(port);
  }

  getSessionsByPort(port: number): ClientSession[] {
    const results: ClientSession[] = [];
    for (const session of this.sessionsByAddr.values()) {
      if (session.localPort === port) {
        results.push(session);
      }
    }
    return results;
  }

  private pingCounter = 0;

  private tick(): void {
    try {
      this.pingCounter++;
      const now = Date.now();
      for (const session of this.sessionsByAddr.values()) {
        const idleMs = now - session.reliability.getLastReceivedAtMs();
        if (idleMs > this.sessionTimeoutMs) {
          this.handleDisconnect(session, `session timeout (idle ${String(idleMs)}ms)`);
        }
      }
      for (const session of this.sessionsByAddr.values()) {
        if (session.state === ConnectionState.CONNECTED && this.pingCounter % 15 === 0) {
          const ping = new Uint8Array(9);
          ping[0] = 0x00;
          writeU32BE(ping, 5, session.reliability.getTimestampMs());
          session.reliability.queueOutgoing(ping, Reliability.UNRELIABLE);
        }
        const sock = this.sessionSockets.get(addrKey(session.address));
        if (!sock) continue;
        const packets = session.reliability.getOutgoingPackets();
        for (const p of packets) {
          sock.sendTo(p, session.address.host, session.address.port);
        }
        const retransmits = session.reliability.getRetransmitPackets();
        for (const p of retransmits) {
          sock.sendTo(p, session.address.host, session.address.port);
        }
      }
    } catch (err) {
      console.error('[RakNet] server tick error:', err);
    }
  }

  private handlePacket(data: Uint8Array, remote: AddressInfo, sock: UdpSocket): void {
    try {
      const first = data[0] ?? 0;
      const routeKey = addrKey(remote);

      if (first === 0x09) {
        this.handleOpenConnectionRequest(remote, data, routeKey, sock);
        return;
      }

      const session = this.sessionsByAddr.get(routeKey);
      if (!session) return;

      const messages = session.reliability.processIncoming(data);
      for (const msg of messages) {
        if (!msg.payload.length) continue;
        const msgId = msg.payload[0] ?? 0;
        const handled = this.handleInternal(session, msgId, msg.payload);
        if (!handled) {
          for (const h of this.messageHandlers) {
            h(session, msg);
          }
        }
      }
    } catch (err) {
      console.error(`[RakNet] error handling packet from ${remote.host}:${remote.port}:`, err);
    }
  }

  private handleInternal(session: ClientSession, msgId: number, payload: Uint8Array): boolean {
    if (msgId === 0x04) {
      this.handleConnectionRequest(session, payload);
      return true;
    }
    if (msgId === 0x11) {
      return true;
    }
    if (msgId === 0x00) {
      this.handlePing(session, payload);
      return true;
    }
    if (msgId === 0x03) {
      return true;
    }
    if (msgId === 0x83) {
      this.handlePlayerReady(session);
      return true;
    }
    if (msgId === 0x13 || msgId === 0x15) {
      this.handleDisconnect(session);
      return true;
    }
    return false;
  }

  private handleOpenConnectionRequest(
    remote: AddressInfo,
    data: Uint8Array,
    routeKey: string,
    sock: UdpSocket,
  ): void {
    const localPort = this.getSocketPort(sock);
    if (!this.portAccepting.get(localPort)) return;

    const clientGuidUpper = data.slice(2, 6);
    const launchId = data.length >= 10
      ? new DataView(data.buffer, data.byteOffset + 2, 8).getBigUint64(0)
      : 0n;
    const reply = new Uint8Array(MTU_SIZE);
    reply[0] = 0x0a;
    reply.set(OFFLINE_MAGIC, 1);
    reply.set(clientGuidUpper, 17);
    const serverNonce = new Uint8Array(4);
    for (let i = 0; i < 4; i++) serverNonce[i] = Math.floor(Math.random() * 256);
    reply.set(serverNonce, 21);
    reply.set(encodeAddress(remote.host, remote.port), 25);
    sock.sendTo(reply, remote.host, remote.port);

    // Retransmitted open-connection requests from a known address reuse
    // the existing session (same id); only a new address mints a session.
    if (!this.sessionsByAddr.has(routeKey)) {
      const session: ClientSession = {
        id: randomUUID(),
        address: remote,
        playerIndex: 0,
        viewIdBase: 0,
        viewIdEnd: 0,
        state: ConnectionState.CONNECTING,
        reliability: new ReliabilityLayer(remote, this.epochNs),
        perGameLaunchId: launchId,
        localPort,
      };
      this.sessionsByAddr.set(routeKey, session);
      this.sessionsById.set(session.id, session);
      this.sessionSockets.set(routeKey, sock);
    }
  }

  private getSocketPort(sock: UdpSocket): number {
    for (const [port, s] of this.sockets) {
      if (s === sock) return port;
    }
    return 0;
  }

  /** Remove a session from ALL maps (routing + identity + socket). */
  private removeSession(session: ClientSession): void {
    const key = addrKey(session.address);
    this.sessionsByAddr.delete(key);
    this.sessionsById.delete(session.id);
    this.sessionSockets.delete(key);
  }

  private handleConnectionRequest(session: ClientSession, payload: Uint8Array): void {
    const pwOffset = 1 + 16 + 8;
    const pwBytes = payload.slice(pwOffset);
    let clientPw = '';
    for (let i = 0; i < pwBytes.length; i++) {
      const b = pwBytes[i] ?? 0;
      if (b === 0) break;
      clientPw += String.fromCharCode(b);
    }

    if (this.passwordPredicate) {
      if (!this.passwordPredicate(session, clientPw)) {
        this.removeSession(session);
        return;
      }
    } else if (this.password) {
      if (clientPw !== this.password) {
        this.removeSession(session);
        return;
      }
    }

    const buf = new Uint8Array(1 + 6 + 2 + 10 * 6);
    buf[0] = 0x0e;
    buf.set(encodeAddress(session.address.host, session.address.port), 1);
    buf.set(encodeAddress('127.0.0.1', session.localPort), 9);
    buf.set(encodeAddress('127.0.0.1', session.localPort), 15);
    buf.set(encodeAddress('127.0.0.1', session.localPort), 21);
    for (let i = 0; i < 7; i++) {
      buf.set(encodeAddress('0.0.0.0', 65535), 27 + i * 6);
    }
    session.reliability.queueOutgoing(buf, Reliability.RELIABLE_ORDERED);
  }

  private handlePlayerReady(session: ClientSession): void {
    const playerIdx = this.freePlayerIndices.length > 0
      ? this.freePlayerIndices.shift()!
      : this.nextPlayerIndex++;
    session.playerIndex = playerIdx;

    const blockStart = playerIdx * 2 - 1;
    const blockEnd = playerIdx * 2;
    session.viewIdBase = blockStart * this.viewIdStride;
    session.viewIdEnd = blockEnd * this.viewIdStride;

    const buf = new Uint8Array(29);
    buf[0] = 0x81;
    writeU32BE(buf, 1, 1);
    writeU32BE(buf, 5, 0);
    writeU32BE(buf, 9, playerIdx);
    writeU32BE(buf, 13, this.viewIdStride);
    writeU32BE(buf, 17, 2);
    writeU32BE(buf, 21, blockStart);
    writeU32BE(buf, 25, blockEnd);
    session.reliability.queueOutgoing(buf, Reliability.RELIABLE_ORDERED);

    session.state = ConnectionState.CONNECTED;
    for (const h of this.connectHandlers) {
      try { h(session); } catch (err) { console.error('[RakNet] connect handler error:', err); }
    }
  }

  disconnectClient(session: ClientSession): void {
    if (session.state !== ConnectionState.CONNECTED) return;
    session.reliability.queueOutgoing(
      new Uint8Array([MessageId.DISCONNECTION_NOTIFICATION]),
      Reliability.RELIABLE_ORDERED,
    );
    const sock = this.sessionSockets.get(addrKey(session.address));
    if (sock) {
      const packets = session.reliability.getOutgoingPackets();
      for (const p of packets) {
        sock.sendTo(p, session.address.host, session.address.port);
      }
    }
    this.handleDisconnect(session, 'server-initiated disconnect');
  }

  private handleDisconnect(session: ClientSession, reason = 'client disconnect'): void {
    session.state = ConnectionState.DISCONNECTED;
    if (session.playerIndex > 0) {
      this.freePlayerIndices.push(session.playerIndex);
    }
    this.removeSession(session);
    console.log(
      `[RakNet] session ${session.id} (${session.address.host}:${String(session.address.port)}) removed: ${reason}`,
    );
    for (const h of this.disconnectHandlers) {
      try { h(session); } catch (err) { console.error('[RakNet] disconnect handler error:', err); }
    }
  }

  private handlePing(session: ClientSession, payload: Uint8Array): void {
    if (payload.length < 9) return;
    const pong = new Uint8Array(17);
    pong[0] = 0x03;
    pong.set(payload.subarray(1, 9), 1);
    writeU32BE(pong, 13, session.reliability.getTimestampMs());
    session.reliability.queueOutgoing(pong, Reliability.UNRELIABLE);
  }
}

export class RakNetClient {
  private socket: UdpSocket;
  private reliability: ReliabilityLayer | null = null;
  private _state: ConnectionState = ConnectionState.DISCONNECTED;
  private _playerIndex = 0;
  private _viewIdBase = 0;
  private serverHost = '';
  private serverPort = 0;
  private localPort = 0;
  private guid: Uint8Array;
  private _password = '';
  private mtuSize = MTU_SIZE;
  private preBound = false;
  private unsubscribeSocket: (() => void) | null = null;
  private messageHandlers: Array<EventHandler<[IncomingMessage]>> = [];
  private disconnectHandlers: Array<EventHandler<[]>> = [];
  private connectHandlers: Array<EventHandler<[]>> = [];
  private tickTimer: ReturnType<typeof setInterval> | null = null;

  constructor(socket: UdpSocket) {
    this.socket = socket;
    this.guid = randomGuid();
  }

  get connected(): boolean {
    return this._state === ConnectionState.CONNECTED;
  }

  get playerIndex(): number {
    return this._playerIndex;
  }

  get viewIdBase(): number {
    return this._viewIdBase;
  }

  get state(): ConnectionState {
    return this._state;
  }

  async connect(
    host: string,
    port: number,
    options?: { password?: string; timeout?: number; localAddress?: string; mtu?: number; preBound?: boolean },
  ): Promise<void> {
    this.serverHost = host;
    this.serverPort = port;
    this._password = options?.password ?? '';
    this.mtuSize = options?.mtu ?? MTU_SIZE;
    this.preBound = options?.preBound ?? false;
    const timeout = options?.timeout ?? 5000;

    this.unsubscribeSocket = this.socket.addMessageHandler((data, remote) => {
      if (remote.host !== this.serverHost || remote.port !== this.serverPort) return;
      this.handlePacket(data);
    });
    if (!this.preBound) {
      await this.socket.bind(0, options?.localAddress);
    }
    this.localPort = this.socket.localPort ?? 0;

    this.reliability = new ReliabilityLayer({ host, port });
    this._state = ConnectionState.CONNECTING;

    this.sendOpenConnectionRequest();

    this.tickTimer = setInterval(() => {
      this.tick();
    }, 66);

    await new Promise<void>((resolve, reject) => {
      let settled = false;
      const timer = setTimeout(() => {
        if (settled) return;
        settled = true;
        this._state = ConnectionState.DISCONNECTED;
        if (this.tickTimer) {
          clearInterval(this.tickTimer);
          this.tickTimer = null;
        }
        this.unsubscribeSocket?.();
        this.unsubscribeSocket = null;
        if (!this.preBound) this.socket.close().catch(() => {});
        reject(new Error('Connection timed out'));
      }, timeout);

      const checkConnect = (): void => {
        if (settled) return;
        if (this._state === ConnectionState.CONNECTED) {
          settled = true;
          clearTimeout(timer);
          resolve();
        } else if (this._state === ConnectionState.DISCONNECTED) {
          settled = true;
          clearTimeout(timer);
          if (this.tickTimer) {
            clearInterval(this.tickTimer);
            this.tickTimer = null;
          }
          reject(new Error('Connection failed'));
        } else {
          setTimeout(checkConnect, 10);
        }
      };
      checkConnect();
    });
  }

  disconnect(): void {
    if (this.reliability && this._state === ConnectionState.CONNECTED) {
      this.reliability.queueOutgoing(
        new Uint8Array([MessageId.DISCONNECTION_NOTIFICATION]),
        Reliability.RELIABLE_ORDERED,
      );
      const packets = this.reliability.getOutgoingPackets();
      for (const p of packets) {
        this.socket.sendTo(p, this.serverHost, this.serverPort);
      }
    }
    this._state = ConnectionState.DISCONNECTED;
    if (this.tickTimer) {
      clearInterval(this.tickTimer);
      this.tickTimer = null;
    }
  }

  async close(): Promise<void> {
    this.disconnect();
    this.unsubscribeSocket?.();
    this.unsubscribeSocket = null;
    if (!this.preBound) await this.socket.close();
  }

  send(payload: Uint8Array, reliability: Reliability, bitLength?: number): void {
    if (this.reliability) {
      this.reliability.queueOutgoing(payload, reliability, 0, bitLength);
    }
  }

  onMessage(handler: EventHandler<[IncomingMessage]>): void {
    this.messageHandlers.push(handler);
  }

  onDisconnect(handler: EventHandler<[]>): void {
    this.disconnectHandlers.push(handler);
  }

  onConnect(handler: EventHandler<[]>): void {
    this.connectHandlers.push(handler);
  }

  private tick(): void {
    try {
      if (!this.reliability) return;
      const packets = this.reliability.getOutgoingPackets();
      for (const p of packets) {
        this.socket.sendTo(p, this.serverHost, this.serverPort);
      }
      const retransmits = this.reliability.getRetransmitPackets();
      for (const p of retransmits) {
        this.socket.sendTo(p, this.serverHost, this.serverPort);
      }
    } catch (err) {
      console.error('[RakNet] client tick error:', err);
    }
  }

  private handlePacket(data: Uint8Array): void {
    try {
      const first = data[0] ?? 0;

      if (first === 0x0a) {
        this.handleOpenConnectionReply();
        return;
      }

      if (!this.reliability) return;

      const messages = this.reliability.processIncoming(data);
      for (const msg of messages) {
        if (!msg.payload.length) continue;
        const msgId = msg.payload[0] ?? 0;
        const handled = this.handleInternal(msgId, msg.payload);
        if (!handled) {
          for (const h of this.messageHandlers) {
            h(msg);
          }
        }
      }
    } catch (err) {
      console.error('[RakNet] error handling packet:', err);
    }
  }

  private handleInternal(msgId: number, payload: Uint8Array): boolean {
    if (msgId === 0x0e) {
      this.handleConnectionAccepted(payload);
      return true;
    }
    if (msgId === 0x00) {
      this.handlePing(payload);
      return true;
    }
    if (msgId === 0x03) {
      return true;
    }
    if (msgId === 0x81) {
      this.handlePlayerAssignment(payload);
      return true;
    }
    if (msgId === 0x15) {
      this._state = ConnectionState.DISCONNECTED;
      for (const h of this.disconnectHandlers) {
        try { h(); } catch (err) { console.error('[RakNet] disconnect handler error:', err); }
      }
      return true;
    }
    return false;
  }

  private sendOpenConnectionRequest(): void {
    const buf = new Uint8Array(this.mtuSize);
    buf[0] = 0x09;
    buf[1] = RAKNET_PROTOCOL_VERSION;
    buf.set(this.guid, 2);
    buf.set(OFFLINE_MAGIC, 10);
    buf.set(encodeAddress(this.serverHost, this.serverPort), 26);
    this.socket.sendTo(buf, this.serverHost, this.serverPort);
  }

  private handleOpenConnectionReply(): void {
    this.sendConnectionRequest();
  }

  private sendConnectionRequest(): void {
    if (!this.reliability) return;
    const pwBytes = new TextEncoder().encode(this._password);
    const buf = new Uint8Array(1 + 16 + 8 + pwBytes.length);
    buf[0] = 0x04;
    buf.set(OFFLINE_MAGIC, 1);
    buf.set(this.guid, 17);
    buf.set(pwBytes, 25);
    this.reliability.queueOutgoing(buf, Reliability.RELIABLE);
  }

  private handleConnectionAccepted(_payload: Uint8Array): void {
    if (!this.reliability) return;
    const serverAddr = encodeAddress(this.serverHost, this.serverPort);
    const localAddr = encodeAddress('127.0.0.1', this.localPort);
    const emptyAddr = encodeAddress('0.0.0.0', 65535);

    const buf = new Uint8Array(1 + 6 + 6 + 6 + 8 * 6);
    buf[0] = 0x11;
    buf.set(serverAddr, 1);
    buf.set(localAddr, 7);
    buf.set(localAddr, 13);
    for (let i = 0; i < 8; i++) {
      buf.set(emptyAddr, 19 + i * 6);
    }
    this.reliability.queueOutgoing(buf, Reliability.RELIABLE_ORDERED);

    const ready = new Uint8Array(5);
    ready[0] = 0x83;
    writeU32BE(ready, 1, 1);
    this.reliability.queueOutgoing(ready, Reliability.RELIABLE_ORDERED);

    // Transition to CONNECTED now. Unity game servers send 0x81 (player
    // assignment) in response to 0x83 and we update playerIndex/viewIdBase
    // from it, but non-Unity RakNet servers (e.g. the master server) never
    // send 0x81. The connection is usable after 0x83 either way.
    this._state = ConnectionState.CONNECTED;
    for (const h of this.connectHandlers) {
      try { h(); } catch (err) { console.error('[RakNet] connect handler error:', err); }
    }
  }

  private handlePlayerAssignment(payload: Uint8Array): void {
    if (payload.length >= 13) {
      this._playerIndex = readU32BE(payload, 9);
    }
    if (payload.length >= 17) {
      this._viewIdBase = readU32BE(payload, 13);
    }
    if (payload.length >= 25) {
      const blockStart = readU32BE(payload, 21);
      this._viewIdBase = blockStart * this._viewIdBase;
    }
  }

  private handlePing(payload: Uint8Array): void {
    if (!this.reliability || payload.length < 9) return;
    const pong = new Uint8Array(17);
    pong[0] = 0x03;
    pong.set(payload.subarray(1, 9), 1);
    writeU32BE(pong, 13, this.reliability.getTimestampMs());
    this.reliability.queueOutgoing(pong, Reliability.UNRELIABLE);
  }
}
